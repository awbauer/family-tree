// The research section: overview, data problems, findings, to-dos, suggestions, agent runs, verification and
// sources.
import { useMemo, useState } from "react";
import { Link, useParams } from "react-router";
import { useData } from "../../data";
import { isUnknown, PersonLink, useTitle, years } from "../../lib";
import { Inline } from "../../StoryText";
import { byBirth, findingsFor } from "../../tree";
import { Finding, Issue, Linkify, StatusBadge } from "../../ui";
import { AgentRuns } from "./AgentRuns";
import { Queue } from "./Queue";
import { Todos } from "./Todos";

const ISSUE_LABELS: Record<string, string> = { "possible-duplicate": "Possible duplicates", "multiple-parents": "Attached to two sets of parents", "sex-role": "Sex conflicts with role", "parent-age": "Impossible parent ages", "born-after-parent-death": "Born after a parent died", "misfiled-event": "Relatives’ events misfiled", "conflicting-dates": "Records disagree on dates", "conflicting-places": "Records disagree on places", "anachronistic-place": "Anachronistic place names", "date-format": "Badly formatted dates", "missing-sex": "Missing sex", "marriage-age": "Implausible marriage ages", "death-before-birth": "Death before birth", age: "Implausible lifespans" };
const SEVERITY = ["error", "warn", "info"];
const PRIORITY: Record<string, number> = { high: 0, medium: 1, low: 2 };
const KIND_ORDER: Record<string, number> = { correction: 0, "data-error": 0, conflict: 1, "new-person": 2, "new-fact": 3, confirmed: 4 };

function Overview() {
  const { D, live, editor, tree, account } = useData();
  const R: any = D.research, findings: any[] = R.findings || [], todos: any[] = R.todo || [], issues: any[] = (D as any).issues || [];
  const k: Record<string, number> = {};
  findings.forEach((f) => (k[f.kind] = (k[f.kind] || 0) + 1));
  return (
    <>
      <div className="prose"><p>This tree began as an Ancestry export. Ancestry trees are easy to grow and easy to get wrong: record “hints” get attached to the wrong person, duplicates creep in, and other people’s unsourced trees get copied. This section tracks what has actually been checked against records, what is wrong, and what to do next.</p></div>
      <div className="grid g4">
        <div className="card"><div className="eyebrow">Findings</div><div className="stat"><b>{findings.length}</b></div><p className="small">{Object.entries(k).map(([a, b]) => `${b} ${a}`).join(" · ") || "none yet"}</p><Link className="small" to="/research/findings">Review →</Link></div>
        <div className="card"><div className="eyebrow">Data problems</div><div className="stat"><b>{issues.filter((i) => i.severity === "error").length}</b></div><p className="small">errors, plus {issues.filter((i) => i.severity === "warn").length} warnings, found automatically on each build.</p><Link className="small" to="/research/review">Review →</Link></div>
        <div className="card"><div className="eyebrow">Open tasks</div><div className="stat"><b>{todos.length}</b></div><p className="small">{todos.filter((t) => t.priority === "high").length} high priority</p><Link className="small" to="/research/todo">See list →</Link></div>
        <div className="card"><div className="eyebrow">Sources</div><div className="stat"><b>{Object.keys(D.sources).length}</b></div><p className="small">record collections cited from Ancestry</p><Link className="small" to="/research/sources">Browse →</Link></div>
      </div>
      {live && editor && (
        <p className="btn-row" style={{ marginTop: 14 }}>
          <a className="btn" href={`api/export.gedcomx?tree=${encodeURIComponent(tree || "")}`} download title="GEDCOM X JSON: the full model, with evidence and provenance">Download GEDCOM X</a>
          <a className="btn" href={`api/export.ged?tree=${encodeURIComponent(tree || "")}`} download title="GEDCOM 5.5.1, for Ancestry and older software">Download GEDCOM 5.5.1</a>
          {account && account.isOwner && <a className="btn" href="api/export.json" download>Download everything (JSON)</a>}
        </p>
      )}
      {R.methodology && <section className="section prose">{String(R.methodology).split(/\n\n+/).map((t, i) => <p key={i}><Inline text={t} /></p>)}</section>}
    </>
  );
}

function Review() {
  const { D } = useData();
  const issues: any[] = (D as any).issues || [];
  const groups: Record<string, any[]> = {};
  issues.forEach((i) => (groups[i.kind] = groups[i.kind] || []).push(i));
  return (
    <>
      <p className="muted">Generated by <code>tools/build.py</code> on every build, so this list shrinks as you fix things in Ancestry and re-export.</p>
      {Object.entries(groups).sort((a, b) => SEVERITY.indexOf(a[1][0].severity) - SEVERITY.indexOf(b[1][0].severity)).map(([k, list]) => (
        <section key={k} className="card" style={{ marginBottom: 14 }}><h3>{ISSUE_LABELS[k] || k} <span className="count">{list.length}</span></h3>{list.map((i, j) => <Issue key={j} i={i} />)}</section>
      ))}
    </>
  );
}

function Findings() {
  const { D } = useData();
  const R: any = D.research, findings: any[] = R.findings || [];
  const [k, setK] = useState(""), [b, setB] = useState(""), [c, setC] = useState("");
  const list = findings.filter((f) => (!k || f.kind === k) && (!c || f.confidence === c) && (!b || (f.person && D.people[f.person] && D.people[f.person].branch === b) || (!f.person && f.branch === b)))
    .sort((x, y) => (KIND_ORDER[x.kind] ?? 5) - (KIND_ORDER[y.kind] ?? 5));
  return (
    <>
      <div className="filters">
        <select id="ff-k" value={k} onChange={(e) => setK(e.target.value)}><option value="">All kinds</option>{[...new Set(findings.map((f) => f.kind))].map((x) => <option key={x}>{x}</option>)}</select>
        <select id="ff-b" value={b} onChange={(e) => setB(e.target.value)}><option value="">All branches</option>{(R.branches || []).map((x: any) => <option key={x.key} value={x.key}>{x.label}</option>)}</select>
        <select id="ff-c" value={c} onChange={(e) => setC(e.target.value)}><option value="">Any confidence</option><option>high</option><option>medium</option><option>low</option></select>
      </div>
      <div id="ff-out">{list.length ? list.map((f, i) => <Finding key={f.id ?? i} f={f} />) : <div className="empty">No findings match.</div>}</div>
    </>
  );
}

/** The to-do list on the static preview (no API): the to-dos in the tree. */
function StaticTodos() {
  const { D } = useData();
  const todos: any[] = (D.research as any).todo || [];
  if (!todos.length) return <div className="empty">No tasks yet.</div>;
  return (
    <div className="table-wrap"><table className="data"><thead><tr><th>Priority</th><th>Person</th><th>Task</th><th>Where to look</th></tr></thead><tbody>
      {todos.slice().sort((a, b) => PRIORITY[a.priority] - PRIORITY[b.priority]).map((t, i) => (
        <tr key={t.id ?? i}><td className={`prio-${t.priority}`}>{t.priority}</td><td>{t.person && D.people[t.person] ? <PersonLink id={t.person} /> : "—"}</td><td>{t.task}</td><td className="small"><Linkify text={t.where || ""} /></td></tr>
      ))}
    </tbody></table></div>
  );
}

function Verification() {
  const { D, people } = useData();
  const list = people.filter((p: any) => !isUnknown(p) && p.direct).sort((a: any, b: any) => a.generation - b.generation || byBirth(D)(a.id, b.id));
  return (
    <>
      <p className="muted">Direct ancestors, by generation. Status is set in <code>research.json → people_status</code>.</p>
      <div className="table-wrap"><table className="data"><thead><tr><th>Gen</th><th>Person</th><th>Status</th><th>Note</th><th>Findings</th></tr></thead><tbody>
        {list.map((p: any) => (
          <tr key={p.id}><td>{p.generation}</td><td><PersonLink id={p.id} /><br /><span className="small muted">{years(p)} · {p.relation || ""}</span></td>
            <td><StatusBadge status={p.status} note={p.statusNote} /></td><td className="small">{p.statusNote}</td><td>{findingsFor(D, p.id).length || ""}</td></tr>
        ))}
      </tbody></table></div>
    </>
  );
}

function Sources() {
  const { D, people } = useData();
  const { use, list } = useMemo(() => {
    const use: Record<string, string[]> = {};
    people.forEach((p: any) => {
      const seen = new Set<string>();
      p.events.concat([{ citations: p.citations }]).forEach((e: any) => (e.citations || []).forEach((c: any) => {
        if (!seen.has(c.source)) { seen.add(c.source); (use[c.source] = use[c.source] || []).push(p.id); }
      }));
    });
    const list = Object.values(D.sources as Record<string, any>).sort((a, b) => (use[b.id] || []).length - (use[a.id] || []).length);
    return { use, list };
  }, [D, people]);
  return (
    <>
      <p className="muted">Every record collection cited in the Ancestry export, with the people who cite it. Indexes (e.g. “Find a Grave Index”, “Public Records Index”) are pointers, not proof — follow them to the underlying record.</p>
      <div className="table-wrap"><table className="data"><thead><tr><th>Collection</th><th>People</th></tr></thead><tbody>
        {list.map((s) => (
          <tr key={s.id}><td>{s.title}<br /><span className="small muted">{s.author || ""}</span></td>
            <td className="small">{(use[s.id] || []).length ? use[s.id].map((id, i) => <span key={id}>{i > 0 && ", "}<PersonLink id={id} /></span>) : "—"}</td></tr>
        ))}
      </tbody></table></div>
    </>
  );
}

export function Research() {
  const { tab: t } = useParams();
  const tab = t || "overview";
  const { D, live, ai } = useData();
  useTitle("Research");
  const R: any = D.research, issues: any[] = (D as any).issues || [];
  const tabs: [string, string, number | null][] = [
    ["overview", "Overview", null], ["review", "Data problems", issues.filter((i) => i.severity !== "info").length],
    ["findings", "Findings", (R.findings || []).length], ["todo", "To-do", (R.todo || []).length],
    ...(live ? [["queue", "Suggestions", null] as [string, string, null]] : []), ...(ai ? [["agents", "Agent runs", null] as [string, string, null]] : []),
    ["status", "Verification", null], ["sources", "Sources", Object.keys(D.sources).length],
  ];
  let body = null;
  if (tab === "overview") body = <Overview />;
  else if (tab === "review") body = <Review />;
  else if (tab === "findings") body = <Findings />;
  else if (tab === "todo") body = live ? <Todos /> : <StaticTodos />;
  else if (tab === "queue" && live) body = <Queue />;
  else if (tab === "agents" && ai) body = <AgentRuns />;
  else if (tab === "status") body = <Verification />;
  else if (tab === "sources") body = <Sources />;
  return (
    <div className="wrap page">
      <h1>Research</h1>
      <nav className="tabs">{tabs.map(([k, l, n]) => <Link key={k} to={`/research/${k}`} className={k === tab ? "on" : ""}>{l}{n != null && <span className="count">{n}</span>}</Link>)}</nav>
      {body}
    </div>
  );
}

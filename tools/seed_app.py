#!/usr/bin/env python3
"""One-time import into the app schema (migrations/0001_app_schema.sql). After this, the app is the source of truth.

    python3 tools/build.py --raw-out build/raw.json
    python3 tools/seed_app.py --owner you@example.com            # writes build/seed-app.sql
    npm run db:import                                             # guarded: refuses once the app owns the data

Reads build/raw.json (the tree after grafts and edits, plus the research layer) and build/family.json (for
aliases), and writes INSERTs for people, families, sources, media, config, findings, statuses, stories,
research log and to-dos, plus the trees from research.json → "trees" and the owner's member row.

research.json "trees" (optional; default: one tree with everything):
  [{"id": "mine", "name": "My family", "definition": {"branches": ["*"]}},
   {"id": "spouse", "name": "My spouse's family", "definition": {"branches": ["spouse-branch"], "include": ["I1", "I2"]}}]

The owner email is passed on the command line and only written to the generated SQL (in git-ignored build/).
Pass --cutover to also set meta.source_of_truth = 'app' (locks out db:load / db:import afterwards).
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def j(v):
    return q(json.dumps(v, ensure_ascii=False, separators=(",", ":")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=str(ROOT / "build" / "raw.json"))
    ap.add_argument("--bundle", default=str(ROOT / "build" / "family.json"))
    ap.add_argument("--research", default=str(ROOT / "family-data" / "research.json"))
    ap.add_argument("--out", default=str(ROOT / "build" / "seed-app.sql"))
    ap.add_argument("--owner", required=True, help="owner's email (Access identity)")
    ap.add_argument("--cutover", action="store_true", help="mark the app as the source of truth")
    ap.add_argument("--assign-open-to", default=None, help='assign every open to-do to this principal (an email, or "owner")')
    a = ap.parse_args()

    st = json.loads(Path(a.raw).read_text())
    raw, research, places = st["raw"], st["research"], st.get("places", {})
    bundle = json.loads(Path(a.bundle).read_text()) if Path(a.bundle).exists() else {}
    cfg_src = json.loads(Path(a.research).read_text()) if Path(a.research).exists() else {}
    t = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    who = "import"
    out = ["-- Generated by tools/seed_app.py: one-time import into the app schema. Do not commit.",
           "PRAGMA defer_foreign_keys = true;"]
    for tbl in ("people", "families", "sources", "media", "config", "findings", "statuses", "stories",
                "research_log", "todos", "todo_events", "proposals", "trees", "changes"):
        out.append(f"DELETE FROM {tbl};")

    def assign_fids(ent):  # stable fact ids for events and names (see worker/ops.js assignFids)
        for i, ev in enumerate(ent.get("events", []), 1):
            ev.setdefault("fid", f"e{i}")
        for i, nm in enumerate(ent.get("names", []), 1):
            nm.setdefault("fid", f"n{i}")
    for ent in list(raw["people"].values()) + list(raw["families"].values()):
        assign_fids(ent)
    for tbl, coll in (("people", raw["people"]), ("families", raw["families"]), ("sources", raw["sources"]), ("media", raw["media"])):
        for k, v in coll.items():
            out.append(f"INSERT INTO {tbl} (id, data, updated_at, updated_by) VALUES ({q(k)}, {j(v)}, {q(t)}, {q(who)});")

    config = {k: research.get(k) for k in ("site", "home_person", "core_people", "branches", "place_rules", "overrides",
                                           "duplicates", "methodology", "context") if research.get(k) is not None}
    config["places"] = places
    config["media_map"] = research.get("media", {})
    config["aliases"] = bundle.get("aliases", {})
    for k, v in config.items():
        out.append(f"INSERT INTO config (key, value, updated_at, updated_by) VALUES ({q(k)}, {j(v)}, {q(t)}, {q(who)});")

    for f in research.get("findings", []):
        out.append(f"INSERT INTO findings (person_id, data, created_at, created_by) VALUES ({q(f.get('person') or None)}, {j(f)}, {q(f.get('date') or t)}, {q(f.get('agent') or who)});")
    for pid, s in research.get("people_status", {}).items():
        out.append(f"INSERT INTO statuses (person_id, data, updated_at, updated_by) VALUES ({q(pid)}, {j(s)}, {q(t)}, {q(who)});")
    for s in research.get("stories", []):
        out.append(f"INSERT INTO stories (slug, data, updated_at, updated_by) VALUES ({q(s['slug'])}, {j(s)}, {q(t)}, {q(who)});")
    for l in research.get("research_log", []):
        out.append(f"INSERT INTO research_log (person_id, data, created_at, created_by) VALUES ({q(l.get('person') or None)}, {j(l)}, {q(l.get('date') or t)}, {q(l.get('agent') or who)});")

    assign = a.owner.strip().lower() if a.assign_open_to == "owner" else (a.assign_open_to or "").strip().lower() or None

    def todo(td, status):
        closed = t if status == "done" else None
        who_ = assign if status == "open" else None
        return (f"INSERT INTO todos (person_id, task, location, priority, status, assignee, branch, outcome, created_at, created_by, updated_at, updated_by, closed_at) VALUES "
                f"({q(td.get('person') or None)}, {q(td['task'])}, {q(td.get('where') or None)}, {q(td.get('priority') or 'medium')}, {q(status)}, {q(who_)}, "
                f"{q(td.get('branch'))}, {q(td.get('outcome') or None)}, {q(t)}, {q(who)}, {q(td.get('closed') or t)}, {q(who)}, {q(closed if not td.get('closed') else td['closed'])});")
    for td in research.get("todo", []):
        out.append(todo(td, "open"))
    for td in research.get("todo_done", []):
        out.append(todo(td, "done"))

    trees = cfg_src.get("trees") or [{"id": "family", "name": (research.get("site") or {}).get("familyName") or "Family", "definition": {"branches": ["*"]}}]
    for tr in trees:
        if not tr.get("id") or not tr.get("name") or "definition" not in tr:
            sys.exit("each tree in research.json 'trees' needs id, name and definition")
        out.append(f"INSERT INTO trees (id, name, definition, created_at, updated_at) VALUES ({q(tr['id'])}, {q(tr['name'])}, {j(tr['definition'])}, {q(t)}, {q(t)});")
    owner = a.owner.strip().lower()
    out.append(f"INSERT INTO members (principal, kind, display_name, person_id, is_owner, created_at, invited_by) VALUES "
               f"({q(owner)}, 'person', NULL, {q(research.get('home_person'))}, 1, {q(t)}, 'import') "
               "ON CONFLICT(principal) DO UPDATE SET is_owner = 1;")
    out.append(f"INSERT INTO changes (at, actor, actor_kind, entity_type, entity_id, op, reason) VALUES ({q(t)}, {q(who)}, 'person', 'database', 'all', 'import', 'one-time GEDCOM import');")
    out.append("UPDATE meta SET value = CAST(value AS INTEGER) + 1 WHERE key = 'data_version';")
    if a.cutover:
        out.append("UPDATE meta SET value = 'app' WHERE key = 'source_of_truth';")
    Path(a.out).write_text("\n".join(out) + "\n")
    n_todo = len(research.get("todo", [])) + len(research.get("todo_done", []))
    print(f"Wrote {a.out}: {len(raw['people'])} people, {len(raw['families'])} families, {len(research.get('findings', []))} findings, "
          f"{n_todo} to-dos, {len(trees)} tree(s){', CUTOVER' if a.cutover else ''}")


if __name__ == "__main__":
    main()
